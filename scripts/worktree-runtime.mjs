// Worktree setup, port/data isolation, and cleanup for mcp-gateway.
//
// The primary checkout keeps repository defaults (API/Desktop 127.0.0.1:8789,
// data/dev). Secondary worktrees under .worktrees/ receive a stable
// 12-char hex identity, an unused port slot (1-99), and a worktree-local
// data directory recorded in the ignored .env.worktree file.
import { createHash } from 'node:crypto';
import { execFileSync, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const MARKER = '# MCP_GATEWAY_MANAGED_WORKTREE_ENV_V1';
export const ENV_FILE = '.env.worktree';
export const BASE_SLOT_API_PORT = 8800;
export const MAX_SLOT = 99;

const scriptRepoRoot = fs.realpathSync(fileURLToPath(new URL('..', import.meta.url)));

function fail(message) {
  throw new Error(message);
}

export function sha256Hex(input) {
  return createHash('sha256').update(input).digest('hex');
}

export function worktreeIdentity(canonicalRoot) {
  return sha256Hex(canonicalRoot).slice(0, 12);
}

export function slotPorts(slot) {
  if (!Number.isInteger(slot) || slot < 1 || slot > MAX_SLOT) {
    fail(`invalid worktree slot: ${slot}`);
  }
  return {
    apiPort: BASE_SLOT_API_PORT + slot,
  };
}

export function chooseSlot(id, occupied) {
  const start = Number.parseInt(id.slice(0, 8), 16) % MAX_SLOT;
  for (let offset = 0; offset < MAX_SLOT; offset += 1) {
    const slot = ((start + offset) % MAX_SLOT) + 1;
    if (!occupied.has(slot)) return slot;
  }
  fail('no worktree port slot is available');
}

export function parseManagedEnv(content) {
  if (!content.startsWith(`${MARKER}\n`)) return { managed: false };
  const values = new Map();
  for (const line of content.split('\n')) {
    const match = line.match(/^([A-Z][A-Z0-9_]*)=(.*)$/);
    if (match) values.set(match[1], match[2]);
  }
  return { managed: true, values };
}

export function formatManagedEnv({ id, root, slot }) {
  const { apiPort } = slotPorts(slot);
  const values = [
    ['GATEWAY_WORKTREE_ID', id],
    ['GATEWAY_WORKTREE_PATH', root],
    ['GATEWAY_WORKTREE_SLOT', String(slot)],
    ['GATEWAY_DEV_ADDR', `127.0.0.1:${apiPort}`],
    ['GATEWAY_DEV_DATA_DIR', path.join(root, 'data', 'dev')],
  ];
  return [
    MARKER,
    '# Generated by scripts/worktree-runtime.mjs; do not edit. Rerun `scripts/setup-worktree`.',
    ...values.map(([k, v]) => `${k}=${v}`),
    '',
  ].join('\n');
}

function git(args, cwd) {
  return execFileSync('git', ['-C', cwd, ...args], {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  }).trim();
}

function worktrees(cwd) {
  return git(['worktree', 'list', '--porcelain'], cwd)
    .split('\n')
    .filter((line) => line.startsWith('worktree '))
    .map((line) => line.slice('worktree '.length))
    .filter((wtPath) => {
      try {
        return fs.statSync(wtPath).isDirectory();
      } catch {
        return false;
      }
    })
    .map((wtPath) => fs.realpathSync(wtPath));
}

function primaryRoot(cwd) {
  const first = git(['worktree', 'list', '--porcelain'], cwd).split('\n')[0];
  if (!first?.startsWith('worktree ')) fail('cannot determine the primary checkout');
  return fs.realpathSync(first.slice('worktree '.length));
}

function readManagedEnv(root) {
  const envPath = path.join(root, ENV_FILE);
  let info;
  try {
    info = fs.lstatSync(envPath);
  } catch (error) {
    if (error && error.code === 'ENOENT') return null;
    throw error;
  }
  if (!info.isFile()) fail(`${envPath} must be a regular file`);
  return parseManagedEnv(fs.readFileSync(envPath, 'utf8'));
}

function occupiedSlots(currentRoot, cwd) {
  const slots = new Set();
  for (const wtPath of worktrees(cwd)) {
    if (wtPath === currentRoot) continue;
    const env = readManagedEnv(wtPath);
    if (!env?.managed) continue;
    const raw = env.values.get('GATEWAY_WORKTREE_SLOT') ?? '';
    if (/^\d{1,2}$/.test(raw)) slots.add(Number(raw));
  }
  return slots;
}

function ensureManagedEnv(root) {
  const id = worktreeIdentity(root);
  const existing = readManagedEnv(root);
  if (existing && !existing.managed) {
    fail(`${ENV_FILE} exists and is not managed; refusing to overwrite`);
  }
  const kept = Number(existing?.values.get('GATEWAY_WORKTREE_SLOT'));
  const occupied = occupiedSlots(root, root);
  const slot =
    Number.isInteger(kept) && kept >= 1 && kept <= MAX_SLOT && !occupied.has(kept)
      ? kept
      : chooseSlot(id, occupied);
  const content = formatManagedEnv({ id, root, slot });
  fs.writeFileSync(path.join(root, ENV_FILE), content, { mode: 0o600 });
  const { apiPort } = slotPorts(slot);
  return {
    id,
    slot,
    apiPort,
    dataDir: path.join(root, 'data', 'dev'),
  };
}

export function setupWorktree(targetRoot = scriptRepoRoot) {
  const root = fs.realpathSync(targetRoot);
  const primary = primaryRoot(root);
  let runtime = null;
  if (root !== primary) {
    runtime = ensureManagedEnv(root);
    console.log(
      `worktree ${runtime.id}: api 127.0.0.1:${runtime.apiPort}, data ${runtime.dataDir}`,
    );
  }
  return { root, primary, runtime };
}

export function cleanWorktree(targetPath = scriptRepoRoot) {
  let root;
  try {
    root = fs.realpathSync(targetPath);
  } catch {
    fail(`worktree path does not exist: ${targetPath}`);
  }
  const primary = primaryRoot(root);
  if (root === primary) {
    fail('the primary checkout keeps repository defaults; nothing to clean');
  }
  const env = readManagedEnv(root);
  if (!env) {
    console.log('no managed runtime in this worktree; nothing to clean');
    return { cleaned: false };
  }
  if (!env.managed) {
    fail(`${ENV_FILE} exists and is not managed; refusing to remove`);
  }
  if (git(['status', '--porcelain'], root)) {
    fail('worktree has uncommitted changes; commit, push, or discard them before cleanup');
  }
  fs.rmSync(path.join(root, ENV_FILE));
  console.log(`removed ${ENV_FILE} in ${root}`);
  return { cleaned: true };
}

function ownedRuntimeValues(root) {
  const env = readManagedEnv(root);
  if (!env) fail(`missing ${ENV_FILE}; run scripts/setup-worktree first`);
  if (!env.managed) fail(`${ENV_FILE} exists and is not managed; refusing to use it`);
  const expectedId = worktreeIdentity(root);
  if (env.values.get('GATEWAY_WORKTREE_ID') !== expectedId) {
    fail(`${ENV_FILE} belongs to another path (worktree moved?); rerun scripts/setup-worktree`);
  }
  return Object.fromEntries(env.values);
}

function runTarget(part, extraArgs) {
  const root = fs.realpathSync(process.cwd());
  const primary = primaryRoot(root);
  const isSecondary = root !== primary;
  const values = isSecondary ? ownedRuntimeValues(root) : null;

  let cmd;
  let args;
  let cwd = root;
  const env = { ...process.env };

  if (part === 'api') {
    cmd = path.join(root, 'start.sh');
    args = isSecondary ? ['-addr', values.GATEWAY_DEV_ADDR, ...extraArgs] : extraArgs;
    if (isSecondary) {
      env.GATEWAY_DEV_DATA_DIR = values.GATEWAY_DEV_DATA_DIR;
    }
  } else if (part === 'desktop') {
    cmd = process.execPath;
    args = [
      path.join(root, 'scripts', 'build-channel.mjs'),
      'run',
      'dev',
      ...(isSecondary
        ? ['-addr', values.GATEWAY_DEV_ADDR, '-data', values.GATEWAY_DEV_DATA_DIR]
        : []),
      ...extraArgs,
    ];
  } else {
    fail('usage: worktree-runtime.mjs run api|desktop [args...]');
  }

  const result = spawnSync(cmd, args, { cwd, env, stdio: 'inherit' });
  if (result.error) throw result.error;
  process.exit(result.status ?? 1);
}

function main() {
  const [command = 'setup', ...rest] = process.argv.slice(2);
  switch (command) {
    case 'setup': {
      const target = rest.find((arg) => !arg.startsWith('--')) ?? process.cwd();
      setupWorktree(target);
      break;
    }
    case 'clean': {
      const target = rest.find((arg) => !arg.startsWith('--')) ?? process.cwd();
      cleanWorktree(target);
      break;
    }
    case 'run': {
      const [part = '', ...extraArgs] = rest;
      runTarget(part, extraArgs);
      break;
    }
    default:
      fail(
        'usage: worktree-runtime.mjs setup [path] | clean [path] | run api|desktop [args...]',
      );
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main();
  } catch (error) {
    console.error(`worktree-runtime: ${error instanceof Error ? error.message : String(error)}`);
    process.exit(1);
  }
}
